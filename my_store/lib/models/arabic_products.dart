/// بتحوّل المنتج لنسخة عربية (إذا موجودة)، وإلا بترجعه زي ما هو
Product toArabic(Product p) {
  final data = _arabicData[p.id];
  if (data == null) return p;
  return Product(
    id: p.id,
    title: data[0],
    price: p.price,
    description: data[1],
    image: p.image,
    category: p.category,
    rating: p.rating,
    ratingCount: p.ratingCount,
  );
}